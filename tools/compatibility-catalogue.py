#!/usr/bin/env python3
"""Validate curated evidence and render docs/DEVICES.md. No network or support inference."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CATALOGUE = ROOT / "compatibility/catalogue.json"
OUTPUT = ROOT / "docs/DEVICES.md"
HALO = {
    "validated": "Validated locally",
    "experimental_rgb": "RGB integration experimental; TV untested",
    "experimental_full_frame": "Full-frame adapter experimental; TV untested",
    "candidate": "Candidate; TV untested",
    "not_integrated": "Adapter not integrated",
    "research": "Research only",
}


def validate(data):
    def require(ok, message):
        if not ok:
            raise ValueError(message)
    require(data.get("schema_version") == 1, "Unsupported catalogue schema")
    require(re.fullmatch(r"\d{4}-\d{2}-\d{2}", data.get("last_reviewed", "")), "Missing review date")
    sources = {}
    for source in data["sources"]:
        sid = source["id"]
        require(sid not in sources, "Duplicate source: " + sid)
        require(re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", source["repository"]), "Invalid repository: " + sid)
        require(re.fullmatch(r"[a-f0-9]{40}", source["commit"]), "Source must pin a full commit: " + sid)
        require(source["ref_kind"] in {"default_branch", "open_pr", "local_reference"}, "Unknown source kind: " + sid)
        require(bool(source["license"]), "Missing license: " + sid)
        if source["ref_kind"] == "open_pr":
            require(source.get("discussion", "").startswith("https://github.com/"), "Missing PR discussion: " + sid)
        sources[sid] = source
    seen = set()
    for device in data["devices"]:
        did = device["id"]
        require(did not in seen, "Duplicate device: " + did)
        seen.add(did)
        require(device["tizenhalo"] in HALO, "Unknown TizenHalo status: " + did)
        require(device["result"] in {"working", "partial", "blocked", "unknown"}, "Unknown result: " + did)
        require(device["evidence"] in {"local_device", "upstream_author", "upstream_user", "research"}, "Unknown evidence: " + did)
        require(bool(device["source_ids"]), "No sources: " + did)
        for sid in device["source_ids"]:
            require(sid in sources, "Unknown source reference: " + sid)
        for key in ("model", "current_tizen", "capture_path", "rate", "observed_scope", "limitations", "checked"):
            require(bool(device.get(key)), "Missing " + key + ": " + did)
        require("firmware" in device, "Use null for unknown firmware: " + did)
        if device["tizenhalo"] == "validated":
            require(device["evidence"] == "local_device" and device["result"] == "working" and bool(device["firmware"]),
                    "Validated support requires local working evidence and exact firmware: " + did)
        for url in device["evidence_urls"]:
            require(url.startswith("https://"), "Invalid evidence URL: " + did)


def render(data):
    validate(data)
    sources = {s["id"]: s for s in data["sources"]}
    def esc(value):
        return str(value).replace("|", "\\|").replace("\n", " ")
    def evidence_links(device):
        links = []
        for sid in device["source_ids"]:
            s = sources[sid]
            url = s.get("discussion") or f'https://github.com/{s["repository"]}/blob/{s["commit"]}/README.md'
            links.append(f"[{sid}]({url})")
        links += [f"[report {i + 1}]({url})" for i, url in enumerate(device["evidence_urls"])]
        return ", ".join(links)
    lines = ["# Device evidence catalogue", "",
             "<!-- Generated by tools/compatibility-catalogue.py from compatibility/catalogue.json. -->", "",
             f'Last reviewed: **{data["last_reviewed"]}**. {data["scope"]}', "",
             "**Only the Q74T entry is validated in TizenHalo.** Working upstream reports are evidence for an adapter, not a TizenHalo support promise.", "",
             "Unknown firmware is shown explicitly. Open PRs are pinned separately from their parent project's default branch.", "",
             "| TV / identifier | Installed Tizen | Published result | Method | TizenHalo | Evidence |",
             "|---|---|---|---|---|---|"]
    for d in data["devices"]:
        lines.append("| " + " | ".join([f'[{esc(d["model"])}](#{d["id"]})', esc(d["current_tizen"]),
                                       esc(d["result"]), esc(d["capture_path"]), HALO[d["tizenhalo"]], evidence_links(d)]) + " |")
    lines += ["", "## Device notes", ""]
    for d in data["devices"]:
        lines += [f'<a id="{d["id"]}"></a>', f'### {d["model"]}', "",
                  f'- Firmware: `{d["firmware"] or "not supplied"}`. Evidence: `{d["evidence"]}`; checked {d["checked"]}.',
                  f'- Observation: {d["observed_scope"]}', f'- Rate: {d["rate"]}',
                  f'- Limits: {d["limitations"]}', f'- Sources: {evidence_links(d)}.', ""]
    lines += ["## Pinned repositories", "", "| Source | Commit | License | Reference |", "|---|---|---|---|"]
    for s in data["sources"]:
        url = f'https://github.com/{s["repository"]}/tree/{s["commit"]}'
        ref = s["ref_kind"]
        if ref == "open_pr":
            ref = f'[open PR; unmerged when checked]({s["discussion"]})'
        lines.append(f'| {s["repository"]} | [{s["commit"][:12]}]({url}) | {s["license"]} | {ref} |')
    lines += ["", "GPL projects are technical references. No GPL implementation is copied into the MIT TizenHalo adapter in this change.", "",
              "## Update procedure", "",
              "1. Read source and follow-up comments; record the exact model, installed OS, firmware and tested source when supplied.",
              "2. Edit `compatibility/catalogue.json`, pin implementation commits and keep missing data explicit.",
              "3. Keep full-frame capture, complete point-set refresh and interpolated LED send rate separate.",
              "4. Run `python3 tools/compatibility-catalogue.py`, then `python3 tools/compatibility-catalogue.py --check`.",
              "5. Update the portability log/handoff. Promote TizenHalo support only with a recorded owner test.", "",
              "See [the plan](PORTABILITY-PLAN.md), [native contracts](CAPTURE-CONTRACTS.md) and [handoff](PORTABILITY-HANDOFF.md).", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed table is stale")
    args = parser.parse_args()
    data = json.loads(CATALOGUE.read_text())
    text = render(data)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit("Device table is stale; run python3 tools/compatibility-catalogue.py")
    else:
        OUTPUT.write_text(text)
    print(f'PASS: {len(data["devices"])} device records, {len(data["sources"])} pinned sources; table current')


if __name__ == "__main__":
    main()
